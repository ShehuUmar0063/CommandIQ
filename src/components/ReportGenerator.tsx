import React, { useState } from 'react';
import {
  AlertCircle,
  BarChart3,
  Bot,
  Calendar,
  CheckCircle2,
  Clock,
  Download,
  Edit3,
  Eye,
  FileCheck,
  FileText,
  Plus,
  RefreshCw,
  Save,
  Sparkles,
  Trash2,
  X,
} from 'lucide-react';
import { jsPDF } from 'jspdf';
import { useApp } from '../context/AppContext';
import { ReportItem, ReportType } from '../types';
import { generateEnterpriseReport } from '../services/api';

export const ReportGenerator: React.FC = () => {
  const {
    reports,
    addReport,
    updateReport,
    deleteReport,
    documents,
    tasks,
    projects,
    knowledge,
    settings,
  } = useApp();

  const [selectedReportType, setSelectedReportType] = useState<ReportType>('Management Summary');
  const [customInstructions, setCustomInstructions] = useState('');
  const [isGenerating, setIsGenerating] = useState(false);
  const [generatedReport, setGeneratedReport] = useState<ReportItem | null>(null);
  const [isEditing, setIsEditing] = useState(false);
  const [editableSummary, setEditableSummary] = useState('');
  const [editableContent, setEditableContent] = useState('');
  const [activeViewingReport, setActiveViewingReport] = useState<ReportItem | null>(null);

  const reportTypes: { type: ReportType; desc: string }[] = [
    {
      type: 'Management Summary',
      desc: 'High-level executive briefing synthesising operations, risks, and critical deadlines.',
    },
    {
      type: 'Weekly Activity Report',
      desc: 'Consolidated weekly summary of completed tasks, ongoing workstreams, and blockers.',
    },
    {
      type: 'Project Progress Report',
      desc: 'Deep-dive review into active milestones, deliverables, and timeline variances.',
    },
    {
      type: 'Task Performance Report',
      desc: 'Audit of task completion velocity, overdue liabilities, and team responsibilities.',
    },
    {
      type: 'Document Analysis Report',
      desc: 'Aggregated findings and strategic takeaways from all uploaded organizational files.',
    },
    {
      type: 'Organisational Overview',
      desc: 'Holistic operational posture report mapping internal policies and business objectives.',
    },
  ];

  // Handle Generate Report via Gemini
  const handleGenerate = async () => {
    setIsGenerating(true);
    setGeneratedReport(null);

    try {
      const contextPayload = {
        orgProfile: settings.orgProfile,
        documents,
        tasks,
        projects,
        orgKnowledge: knowledge,
      };

      const result = await generateEnterpriseReport(
        selectedReportType,
        customInstructions,
        contextPayload
      );

      setGeneratedReport(result);
      setEditableSummary(result.executiveSummary);
      setEditableContent(result.content);
      addReport(result);
    } catch (err: any) {
      alert('Report generation failed: ' + (err.message || 'API error'));
    } finally {
      setIsGenerating(false);
    }
  };

  // Save edits
  const handleSaveEdits = () => {
    if (!generatedReport) return;
    const updated = {
      ...generatedReport,
      executiveSummary: editableSummary,
      content: editableContent,
    };
    setGeneratedReport(updated);
    updateReport(updated.id, updated);
    setIsEditing(false);
  };

  // Download Report as formatted PDF
  const downloadReportAsPDF = (report: ReportItem) => {
    const doc = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4',
    });

    const orgName = settings.orgProfile.name;
    let y = 20;

    // Header Title
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(18);
    doc.setTextColor(15, 23, 42); // slate-900
    doc.text(report.title, 14, y);

    y += 7;
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 116, 139); // slate-500
    doc.text(
      `Generated by CommandIQ • ${orgName} • Date: ${report.generatedDate} • Type: ${report.type}`,
      14,
      y
    );

    y += 10;
    doc.setDrawColor(203, 213, 225); // slate-300
    doc.line(14, y, 196, y);

    y += 8;

    // Executive Summary Section
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(13, 148, 136); // teal-600
    doc.text('1. EXECUTIVE SUMMARY', 14, y);

    y += 6;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(30, 41, 59);
    const summaryLines = doc.splitTextToSize(report.executiveSummary, 180);
    doc.text(summaryLines, 14, y);
    y += summaryLines.length * 5 + 6;

    // Key Findings
    if (report.keyFindings && report.keyFindings.length > 0) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(13, 148, 136);
      doc.text('2. KEY FINDINGS & OBSERVATIONS', 14, y);
      y += 6;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(30, 41, 59);
      for (const finding of report.keyFindings) {
        const lines = doc.splitTextToSize(`• ${finding}`, 180);
        if (y + lines.length * 5 > 280) {
          doc.addPage();
          y = 20;
        }
        doc.text(lines, 14, y);
        y += lines.length * 5 + 1;
      }
      y += 5;
    }

    // Statistics if available
    if (report.statistics && report.statistics.length > 0) {
      if (y > 250) {
        doc.addPage();
        y = 20;
      }
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(13, 148, 136);
      doc.text('3. OPERATIONAL METRICS & KPIS', 14, y);
      y += 6;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      for (const stat of report.statistics) {
        doc.text(`${stat.label}: ${stat.value} ${stat.change ? `(${stat.change})` : ''}`, 14, y);
        y += 5;
      }
      y += 5;
    }

    // Recommendations & Next Steps
    if (report.recommendations && report.recommendations.length > 0) {
      if (y > 250) {
        doc.addPage();
        y = 20;
      }
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(13, 148, 136);
      doc.text('4. STRATEGIC RECOMMENDATIONS', 14, y);
      y += 6;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      for (const rec of report.recommendations) {
        const lines = doc.splitTextToSize(`• ${rec}`, 180);
        if (y + lines.length * 5 > 280) {
          doc.addPage();
          y = 20;
        }
        doc.text(lines, 14, y);
        y += lines.length * 5 + 1;
      }
    }

    // Footer on all pages
    const pageCount = doc.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(
        `CommandIQ Intelligent Enterprise Operations Platform — Confidential — Page ${i} of ${pageCount}`,
        14,
        290
      );
    }

    // Trigger download
    const cleanFileName = report.title.replace(/[^a-zA-Z0-9_-]/g, '_') + '.pdf';
    doc.save(cleanFileName);
  };

  return (
    <div className="p-6 max-w-7xl mx-auto space-y-6">
      {/* Top Header */}
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 p-4 rounded-xl shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-lg font-bold text-slate-900 dark:text-white flex items-center space-x-2">
            <BarChart3 className="w-5 h-5 text-cyan-600 dark:text-cyan-400" />
            <span>AI Report Generator</span>
          </h2>
          <p className="text-xs text-slate-500 dark:text-slate-400">
            Generate executive briefings, audit summaries, and progress reports grounded in live data
          </p>
        </div>

        <div className="text-xs text-slate-400 font-mono">
          <span>Available Data: {documents.length} docs • {tasks.length} tasks • {projects.length} projects</span>
        </div>
      </div>

      {/* Report Generator Control Card */}
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-5 shadow-xs space-y-4">
        <h3 className="text-sm font-bold text-slate-900 dark:text-white uppercase tracking-wider flex items-center space-x-2">
          <Sparkles className="w-4 h-4 text-teal-500" />
          <span>Configure Report Scope</span>
        </h3>

        {/* Report Type Selection Grid */}
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3">
          {reportTypes.map((rt) => {
            const isSelected = selectedReportType === rt.type;
            return (
              <div
                key={rt.type}
                onClick={() => setSelectedReportType(rt.type)}
                className={`p-3.5 rounded-lg border cursor-pointer transition-all ${
                  isSelected
                    ? 'border-teal-500 bg-teal-500/10 text-slate-900 dark:text-white'
                    : 'border-slate-200 dark:border-slate-800 hover:border-slate-300 dark:hover:border-slate-700 bg-slate-50/50 dark:bg-slate-800/40 text-slate-700 dark:text-slate-300'
                }`}
              >
                <div className="flex items-center justify-between">
                  <h4 className="text-xs font-bold">{rt.type}</h4>
                  {isSelected && <CheckCircle2 className="w-4 h-4 text-teal-600 dark:text-teal-400" />}
                </div>
                <p className="text-[11px] text-slate-500 dark:text-slate-400 mt-1 line-clamp-2 leading-relaxed">
                  {rt.desc}
                </p>
              </div>
            );
          })}
        </div>

        {/* Custom Directives / Focus Area */}
        <div>
          <label className="block text-xs font-semibold text-slate-700 dark:text-slate-300 mb-1">
            Optional Focus Areas / Specific Directives
          </label>
          <input
            type="text"
            value={customInstructions}
            onChange={(e) => setCustomInstructions(e.target.value)}
            placeholder="e.g., Focus heavily on European logistics risks and ISO 27001 audit deadlines..."
            className="w-full px-3 py-2 text-xs rounded-lg border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-950 text-slate-900 dark:text-slate-100 focus:outline-none focus:border-teal-500"
          />
        </div>

        {/* Generate Button */}
        <div className="pt-2 flex justify-end">
          <button
            onClick={handleGenerate}
            disabled={isGenerating}
            className="px-5 py-2.5 text-xs font-semibold text-white bg-gradient-to-r from-teal-600 to-cyan-600 hover:from-teal-500 hover:to-cyan-500 rounded-lg shadow-sm flex items-center space-x-2 transition-all cursor-pointer disabled:opacity-60"
          >
            {isGenerating ? (
              <>
                <RefreshCw className="w-4 h-4 animate-spin" />
                <span>Generating Report with Gemini...</span>
              </>
            ) : (
              <>
                <Sparkles className="w-4 h-4" />
                <span>Generate Executive Report</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Generated Report Preview (if freshly generated) */}
      {generatedReport && (
        <div className="bg-white dark:bg-slate-900 border border-teal-500/40 rounded-xl p-6 shadow-md space-y-5 animate-in fade-in">
          {/* Header */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-4 border-b border-slate-100 dark:border-slate-800 gap-3">
            <div>
              <div className="inline-flex items-center space-x-1.5 px-2 py-0.5 rounded bg-teal-500/10 text-teal-600 dark:text-teal-400 text-[10px] font-bold uppercase tracking-wider mb-1">
                <span>Freshly Generated</span>
              </div>
              <h3 className="text-lg font-bold text-slate-900 dark:text-white">
                {generatedReport.title}
              </h3>
              <p className="text-xs text-slate-400">
                Type: {generatedReport.type} • Date: {generatedReport.generatedDate}
              </p>
            </div>

            <div className="flex items-center space-x-2">
              <button
                onClick={() => setIsEditing(!isEditing)}
                className="px-3 py-1.5 text-xs font-medium text-slate-700 dark:text-slate-200 bg-slate-100 hover:bg-slate-200 dark:bg-slate-800 dark:hover:bg-slate-700 rounded-lg transition-colors flex items-center space-x-1 cursor-pointer"
              >
                <Edit3 className="w-3.5 h-3.5" />
                <span>{isEditing ? 'Cancel Edit' : 'Edit Report'}</span>
              </button>

              {isEditing && (
                <button
                  onClick={handleSaveEdits}
                  className="px-3 py-1.5 text-xs font-semibold bg-emerald-600 hover:bg-emerald-500 text-white rounded-lg transition-colors flex items-center space-x-1 cursor-pointer"
                >
                  <Save className="w-3.5 h-3.5" />
                  <span>Save Edits</span>
                </button>
              )}

              <button
                onClick={() => downloadReportAsPDF(generatedReport)}
                className="px-3.5 py-1.5 text-xs font-semibold bg-teal-600 hover:bg-teal-500 text-white rounded-lg transition-colors flex items-center space-x-1.5 cursor-pointer shadow-sm"
              >
                <Download className="w-3.5 h-3.5" />
                <span>Download PDF</span>
              </button>
            </div>
          </div>

          {/* Key Stats Bar */}
          {generatedReport.statistics && generatedReport.statistics.length > 0 && (
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
              {generatedReport.statistics.map((s, idx) => (
                <div
                  key={idx}
                  className="p-3 bg-slate-50 dark:bg-slate-800/50 rounded-lg border border-slate-100 dark:border-slate-800"
                >
                  <span className="text-[11px] text-slate-400 block">{s.label}</span>
                  <span className="text-base font-bold text-slate-900 dark:text-white font-mono">
                    {s.value}
                  </span>
                  {s.change && (
                    <span className="text-[10px] text-teal-600 dark:text-teal-400 block mt-0.5">
                      {s.change}
                    </span>
                  )}
                </div>
              ))}
            </div>
          )}

          {/* Executive Summary */}
          <div>
            <h4 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider mb-1.5">
              Executive Summary
            </h4>
            {isEditing ? (
              <textarea
                value={editableSummary}
                onChange={(e) => setEditableSummary(e.target.value)}
                rows={3}
                className="w-full p-2.5 text-xs border rounded-lg dark:bg-slate-950 dark:border-slate-800 focus:outline-none focus:border-teal-500 leading-relaxed"
              />
            ) : (
              <p className="text-xs text-slate-700 dark:text-slate-300 leading-relaxed bg-slate-50 dark:bg-slate-800/40 p-3.5 rounded-lg border border-slate-100 dark:border-slate-800">
                {generatedReport.executiveSummary}
              </p>
            )}
          </div>

          {/* Key Findings & Recommendations in 2 cols */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-xs">
            {/* Key Findings */}
            <div className="p-4 bg-slate-50 dark:bg-slate-800/40 rounded-lg border border-slate-100 dark:border-slate-800">
              <h4 className="font-bold text-slate-900 dark:text-white mb-2 flex items-center space-x-1.5">
                <FileCheck className="w-4 h-4 text-teal-500" />
                <span>Key Findings</span>
              </h4>
              <ul className="space-y-1.5 list-disc pl-4 text-slate-600 dark:text-slate-300">
                {generatedReport.keyFindings?.map((f, i) => (
                  <li key={i}>{f}</li>
                ))}
              </ul>
            </div>

            {/* Recommendations */}
            <div className="p-4 bg-slate-50 dark:bg-slate-800/40 rounded-lg border border-slate-100 dark:border-slate-800">
              <h4 className="font-bold text-slate-900 dark:text-white mb-2 flex items-center space-x-1.5">
                <CheckCircle2 className="w-4 h-4 text-cyan-500" />
                <span>Recommendations</span>
              </h4>
              <ul className="space-y-1.5 list-disc pl-4 text-slate-600 dark:text-slate-300">
                {generatedReport.recommendations?.map((r, i) => (
                  <li key={i}>{r}</li>
                ))}
              </ul>
            </div>
          </div>

          {/* Full Markdown Body */}
          {generatedReport.content && (
            <div>
              <h4 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider mb-1.5">
                Detailed Report Content
              </h4>
              {isEditing ? (
                <textarea
                  value={editableContent}
                  onChange={(e) => setEditableContent(e.target.value)}
                  rows={8}
                  className="w-full p-2.5 text-xs font-mono border rounded-lg dark:bg-slate-950 dark:border-slate-800 focus:outline-none focus:border-teal-500 leading-relaxed"
                />
              ) : (
                <div className="p-4 bg-slate-50 dark:bg-slate-950 rounded-lg border border-slate-200 dark:border-slate-800 text-xs whitespace-pre-wrap leading-relaxed font-sans">
                  {generatedReport.content}
                </div>
              )}
            </div>
          )}
        </div>
      )}

      {/* Saved Reports Archive */}
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-5 shadow-xs space-y-4">
        <h3 className="text-sm font-bold text-slate-900 dark:text-white flex items-center space-x-2">
          <Clock className="w-4 h-4 text-slate-400" />
          <span>Report Archive ({reports.length})</span>
        </h3>

        <div className="divide-y divide-slate-100 dark:divide-slate-800">
          {reports.map((report) => (
            <div
              key={report.id}
              className="py-3.5 flex flex-col sm:flex-row sm:items-center justify-between gap-3 hover:bg-slate-50/50 dark:hover:bg-slate-800/40 px-2 rounded-lg transition-colors"
            >
              <div>
                <div className="flex items-center space-x-2">
                  <h4 className="text-xs font-bold text-slate-900 dark:text-white">
                    {report.title}
                  </h4>
                  {report.isDemo && (
                    <span className="text-[10px] px-1.5 py-0.2 rounded bg-slate-100 dark:bg-slate-800 text-slate-400 font-mono">
                      Demo
                    </span>
                  )}
                </div>
                <p className="text-[11px] text-slate-500 dark:text-slate-400 mt-0.5 line-clamp-1">
                  {report.executiveSummary}
                </p>
                <div className="flex items-center space-x-2 mt-1 text-[10px] text-slate-400">
                  <span className="font-semibold text-teal-600 dark:text-teal-400">{report.type}</span>
                  <span>•</span>
                  <span>Generated {report.generatedDate}</span>
                </div>
              </div>

              <div className="flex items-center space-x-2 self-end sm:self-auto shrink-0">
                <button
                  onClick={() => downloadReportAsPDF(report)}
                  className="px-2.5 py-1 text-xs font-medium text-slate-700 dark:text-slate-200 bg-slate-100 hover:bg-slate-200 dark:bg-slate-800 dark:hover:bg-slate-700 rounded-md transition-colors flex items-center space-x-1 cursor-pointer"
                  title="Download as PDF"
                >
                  <Download className="w-3.5 h-3.5" />
                  <span>PDF</span>
                </button>

                <button
                  onClick={() => {
                    setGeneratedReport(report);
                    setEditableSummary(report.executiveSummary);
                    setEditableContent(report.content);
                  }}
                  className="p-1.5 text-slate-400 hover:text-slate-700 dark:hover:text-slate-200 rounded-md transition-colors cursor-pointer"
                  title="View / Edit in preview"
                >
                  <Eye className="w-3.5 h-3.5" />
                </button>

                <button
                  onClick={() => deleteReport(report.id)}
                  className="p-1.5 text-slate-400 hover:text-rose-600 rounded-md transition-colors cursor-pointer"
                  title="Delete report"
                >
                  <Trash2 className="w-3.5 h-3.5" />
                </button>
              </div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
};
